for (const [classe, nome] of Object.entries(icones)) {
  const svg = readFileSync(join(pasta, `${nome}.svg`), 'utf8')
    .replace(/ width="48" height="48"/, '')
    .trim();
  const dado = encodeURIComponent(svg).replace(/'/g, '%27');
  linhas.push(`.ic-${classe} {`, `  --ic: url('data:image/svg+xml,${dado}');`, '}', '');
}

writeFileSync(join(raiz, 'src', 'icones.css'), linhas.join('\n'));
